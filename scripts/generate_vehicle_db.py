#!/usr/bin/env python3
"""Embed data/reference/ams2_vehicles_db.json into the C++ binary.

Generates VehicleDb.cpp next to this script's project root: a raw byte array of
the JSON file plus its SHA-256, parsed at runtime by RuleConfig.h's JsonParser.
The app therefore carries the AMS2 vehicle database internally -- no external
data file is shipped or read from disk (see .ai/skills/setup_analysis.md Layer 1).

Usage:
    python scripts/generate_vehicle_db.py [input.json] [output.cpp]

Defaults: input = <root>/data/reference/ams2_vehicles_db.json,
          output = <root>/VehicleDb.cpp   (<root> = parent of this script's dir)
"""
import hashlib
import json
import sys
from pathlib import Path


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "data" / "reference" / "ams2_vehicles_db.json"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "VehicleDb.generated.inc"

    raw = src.read_bytes()
    # Sanity: must be a JSON object of vehicles before we embed it.
    data = json.loads(raw.decode("utf-8"))
    assert isinstance(data, dict), f"{src.name} top level is not an object"
    for name, entry in list(data.items())[:1]:  # spot-check first car shape only (fast)
        assert "physics" in entry and "chassis" in entry["physics"], \
            f"unexpected schema for {name!r}"

    sha = hashlib.sha256(raw).hexdigest()
    n_cars = len(data)

    lines = []
    a = lines.append
    a("//---------------------------------------------------------------------------")
    a("// VehicleDb.cpp -- GENERATED by scripts/generate_vehicle_db.py. DO NOT EDIT.")
    a(f"// Source : data/reference/ams2_vehicles_db.json ({n_cars} vehicles, {len(raw)} bytes)")
    a(f"// SHA-256: {sha}")
    a("// Regenerate after updating the JSON:")
    a("//     python scripts/generate_vehicle_db.py")
    a("//---------------------------------------------------------------------------")
    a("")
    a('#include "VehicleDb.h"')
    a("")

    # Byte array, 24 bytes per line.
    a(f"static const unsigned char kAms2VehiclesJson[{len(raw)}] = {{")
    for i in range(0, len(raw), 24):
        chunk = raw[i:i + 24]
        a("    " + ", ".join(str(b) for b in chunk) + ("," if i + 24 < len(raw) else ""))
    a("};")
    a("")

    # SHA-256 as byte array so tests can compare against the runtime digest.
    sha_bytes = bytes.fromhex(sha)
    a(f"static const unsigned char kAms2VehiclesJsonSha256[32] = {{")
    for i in range(0, 32, 16):
        chunk = sha_bytes[i:i + 16]
        a("    " + ", ".join(str(b) for b in chunk) + ("," if i + 16 < 32 else ""))
    a("};")

    out.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\r\n")
    print(f"OK: {out} ({len(raw)} bytes, sha256={sha[:16]}..., cars={n_cars})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
